/**
 * Common control query parameters accepted on every resource list.
 */
const COMMON_CONTROL_PARAMS = new Set([
  'page',
  'page_size',
  'ordering',
  'since',
  'until',
  'contact',
  'contact_type',
  'external_id',
  'connection_id',
])

/**
 * Filters an arbitrary query params object so only allowed keys are forwarded to DRF.
 * Prevents 400 INVALID_FILTER errors on unknown parameters.
 */
export function filterQueryParams(resourceName, params = {}) {
  const config = RESOURCE_CONFIGS[resourceName]
  if (!config) return {}

  const allowed = new Set(COMMON_CONTROL_PARAMS)
  if (config.supportsSearch) {
    allowed.add('q')
  }
  for (const filter of config.allowedFilters || []) {
    allowed.add(filter)
  }

  const sanitized = {}
  for (const [key, value] of Object.entries(params)) {
    if (value === undefined || value === null || value === '') continue
    if (allowed.has(key)) {
      sanitized[key] = value
    }
  }

  return sanitized
}
